import * as fs from "fs";
import * as path from "path";
import { isUnderRoots, type FsAccess } from "./inputs";
import { JsxToolError } from "./results";

/** `jsx_pull` inline result cap (design section 9.3); larger sources need `outPath`. */
export const MAX_INLINE_JSX_BYTES = 64 * 1024;

/** First line of every file `jsx_pull` writes; only files that start with it may be overwritten. */
export const GENERATED_HEADER = "// @generated by jsx_pull (penpot-mcp-jsx); this file may be overwritten by jsx_pull";

const OUT_EXTENSIONS: readonly string[] = [".tsx", ".jsx"];

function fsDisabled(message: string, hint: string): JsxToolError {
    return new JsxToolError("FS_DISABLED", message, { hint });
}

/**
 * Validates an `outPath` argument without touching the file: local mode, non-empty `fsRoots` (the tool would
 * otherwise write anywhere), absolute, `.tsx`/`.jsx`, parent directory under the roots, target not a symlink,
 * and an existing target only when it carries {@link GENERATED_HEADER}. Call it before any runtime work so a
 * bad path fails early.
 *
 * @returns the resolved target path
 */
export function checkOutPath(outPath: string, fsAccess: FsAccess): string {
    if (!fsAccess.isFileSystemAccessEnabled()) {
        throw fsDisabled(
            "outPath is not available: file system access is disabled (remote or multi-user mode)",
            "omit outPath; the source is returned inline"
        );
    }
    if (fsAccess.fsRoots === undefined || fsAccess.fsRoots.length === 0) {
        throw fsDisabled(
            "outPath is disabled: no allowed roots are configured",
            "set PENPOT_MCP_JSX_FS_ROOTS to enable outPath"
        );
    }
    if (!path.isAbsolute(outPath)) {
        throw new JsxToolError("INVALID_ARGS", `outPath must be an absolute path: ${outPath}`);
    }
    if (!OUT_EXTENSIONS.includes(path.extname(outPath).toLowerCase())) {
        throw new JsxToolError("INVALID_ARGS", `outPath must have one of the extensions ${OUT_EXTENSIONS.join(", ")}`);
    }
    let target: string;
    try {
        target = path.join(fs.realpathSync(path.dirname(outPath)), path.basename(outPath));
    } catch {
        throw new JsxToolError("INVALID_ARGS", "outPath's directory does not exist");
    }
    if (!isUnderRoots(target, fsAccess.fsRoots)) {
        throw new JsxToolError("INVALID_ARGS", "outPath is outside the allowed roots", {
            hint: "see PENPOT_MCP_JSX_FS_ROOTS",
        });
    }
    let stat: fs.Stats | undefined;
    try {
        stat = fs.lstatSync(target);
    } catch {
        stat = undefined;
    }
    if (stat !== undefined) {
        if (stat.isSymbolicLink() || !stat.isFile()) {
            throw new JsxToolError("INVALID_ARGS", "outPath must be a regular file, not a symbolic link");
        }
        if (!hasGeneratedHeader(target)) {
            throw new JsxToolError(
                "INVALID_ARGS",
                "outPath exists and was not written by jsx_pull; refusing to overwrite it",
                { hint: "choose a new file name" }
            );
        }
    }
    return target;
}

function hasGeneratedHeader(file: string): boolean {
    let fd: number | undefined;
    try {
        fd = fs.openSync(file, fs.constants.O_RDONLY | (fs.constants.O_NOFOLLOW ?? 0));
        const buf = Buffer.alloc(GENERATED_HEADER.length + 2);
        const n = fs.readSync(fd, buf, 0, buf.length, 0);
        return buf.subarray(0, n).toString("utf8").split(/\r?\n/, 1)[0] === GENERATED_HEADER;
    } catch {
        return false;
    } finally {
        if (fd !== undefined) fs.closeSync(fd);
    }
}

/**
 * Writes `text` (prefixed by {@link GENERATED_HEADER}) to a validated `outPath`: exclusive create for a new
 * file, no-follow truncating open for a previously generated one.
 *
 * @returns the number of bytes written
 */
export function writeOutput(outPath: string, text: string, fsAccess: FsAccess): number {
    const target = checkOutPath(outPath, fsAccess);
    const body = `${GENERATED_HEADER}\n${text}`;
    const noFollow = fs.constants.O_NOFOLLOW ?? 0;
    try {
        let fd: number;
        try {
            fd = fs.openSync(target, fs.constants.O_WRONLY | fs.constants.O_CREAT | fs.constants.O_EXCL, 0o644);
        } catch (e) {
            if ((e as NodeJS.ErrnoException).code !== "EEXIST") throw e;
            // O_TRUNC without O_CREAT is invalid on Windows, so truncate explicitly after opening
            fd = fs.openSync(target, fs.constants.O_WRONLY | noFollow);
            fs.ftruncateSync(fd, 0);
        }
        try {
            fs.writeSync(fd, body, 0, "utf8");
        } finally {
            fs.closeSync(fd);
        }
    } catch {
        throw new JsxToolError("INVALID_ARGS", "outPath could not be written");
    }
    return Buffer.byteLength(body, "utf8");
}
