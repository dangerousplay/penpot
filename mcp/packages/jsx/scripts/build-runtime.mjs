// Bundles the vendored plugin runtime (src/engine/plugin/entry.ts) into src/generated/runtime.ts.
// RUNTIME_VERSION = sha256(bundle built with a placeholder version).slice(0, 12), then substituted in.
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const PKG_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PLACEHOLDER = "__PENPOT_JSX_VERSION_PLACEHOLDER__";

/** @returns {Promise<{ source: string, version: string, bytes: number }>} */
export async function buildRuntime(pkgDir = PKG_DIR) {
    const result = await build({
        entryPoints: [path.join(pkgDir, "src/engine/plugin/entry.ts")],
        bundle: true,
        write: false,
        format: "iife",
        platform: "browser",
        target: "es2020",
        minify: true,
        legalComments: "none",
        define: { __PENPOT_JSX_VERSION__: JSON.stringify(PLACEHOLDER) },
        logLevel: "silent",
    });
    const placeholderSource = result.outputFiles[0].text.trimEnd();
    const version = createHash("sha256").update(placeholderSource).digest("hex").slice(0, 12);
    const source = placeholderSource.replaceAll(PLACEHOLDER, version);
    return { source, version, bytes: Buffer.byteLength(source, "utf8") };
}

export function renderRuntimeModule({ source, version, bytes }) {
    return [
        "// GENERATED by scripts/build-runtime.mjs from src/engine/plugin/entry.ts. Do not edit; run `pnpm run build:runtime`.",
        `export const RUNTIME_VERSION = ${JSON.stringify(version)};`,
        `export const RUNTIME_BYTES = ${bytes};`,
        `export const RUNTIME_SOURCE = ${JSON.stringify(source)};`,
        "",
    ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const out = await buildRuntime();
    const dest = path.join(PKG_DIR, "src/generated/runtime.ts");
    mkdirSync(path.dirname(dest), { recursive: true });
    writeFileSync(dest, renderRuntimeModule(out));
    console.log(`build:runtime: version ${out.version}, ${out.bytes} bytes -> src/generated/runtime.ts`);
}
